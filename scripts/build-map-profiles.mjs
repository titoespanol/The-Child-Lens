import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync, rmdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import model from '../map/organisation-model.js';

process.chdir(fileURLToPath(new URL('../', import.meta.url)));
const site = 'https://thechildlens.com';
const folder = 'map/organisations';
const check = process.argv.includes('--check');
const stale = [];
function update(file, content) {
  if (!check) {
    writeFileSync(file, content);
    return;
  }
  try {
    if (readFileSync(file, 'utf8') === content) return;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  stale.push(file);
}
const measurementVersion = createHash('sha256').update(readFileSync('map/measurement.js')).digest('hex').slice(0, 12);
const profileStyleVersion = createHash('sha256').update(readFileSync('map/profile-pages.css')).digest('hex').slice(0, 12);
const measurementScript = '/map/measurement.js?v=' + measurementVersion;
const marker = '<!-- Generated by scripts/build-map-profiles.mjs -->';
const rows = JSON.parse(readFileSync('map/data/organisations.json', 'utf8'));
const ids = new Set();
for (const org of rows) {
  if (!/^[a-z0-9][a-z0-9_-]*$/.test(org.id) || !org.name?.trim() || ids.has(org.id)) {
    throw new Error('Invalid or duplicate public listing: ' + org.id);
  }
  ids.add(org.id);
}
if (!ids.size) throw new Error('Empty public directory');
rows.sort((a, b) => a.name.localeCompare(b.name, 'en') || a.id.localeCompare(b.id));
const escape = value => String(value ?? '').replace(/[&<>"']/g, ch => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
})[ch]);
const pathFor = org => '/' + folder + '/' + org.id + '/';
function httpsUrl(value) {
  try {
    const url = new URL(value);
    if (url.protocol === 'https:' && !url.username && !url.password) return url.href;
  } catch {}
}
function link(url, label, event = '') {
  return `<a href="${escape(url)}"${event ? ' data-usage="' + event + '"' : ''}>${escape(label)}</a>`;
}
function render(org) {
  const url = site + pathFor(org);
  const localTitle = org.city && !org.name.toLowerCase().includes(org.city.toLowerCase())
    ? org.name + ' in ' + org.city : org.name;
  const title = localTitle + ' | The Child Lens';
  const place = [org.city, org.country].filter(Boolean).join(', ');
  const description = org.description || [org.name, org.type, place].filter(Boolean).join(' · ');
  const source = httpsUrl(org.sourceUrl);
  const website = httpsUrl(org.website);
  const founded = model.foundingLabel(org);
  const entity = {
    '@type': org.type === "Children's hospital" ? 'Hospital' : 'Organization',
    '@id': url + '#organisation', name: org.name, description: org.description || undefined,
    url: website, address: place ? { '@type': 'PostalAddress', addressLocality: org.city || undefined,
      addressCountry: org.country || undefined } : undefined,
    foundingDate: founded ? String(org.founding_year) : undefined
  };
  const schema = { '@context': 'https://schema.org', '@type': 'WebPage', url, name: title,
    description, mainEntity: entity, citation: source, isPartOf: { '@id': site + '/#website' },
    publisher: { '@id': site + '/#org' },
    breadcrumb: { '@type': 'BreadcrumbList', itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Organisation directory', item: site + '/directory/' },
      { '@type': 'ListItem', position: 2, name: org.name, item: url }
    ] } };
  const details = [
    ['Organisation type', org.type], ['Location', place], ['Stage', org.stage],
    ['Paediatric specialties', org.focus?.join(', ')], ['Technology', org.technology?.join(', ')],
    ['Review status', org.verification]
  ].filter(([, value]) => value).map(([label, value]) =>
    `<dt>${label}</dt><dd>${escape(value)}</dd>`).join('\n');
  const nearby = org.city && org.country ? rows.filter(other => other.id !== org.id &&
    other.city === org.city && other.country === org.country).slice(0, 4) : [];
  const correction = 'mailto:map@thechildlens.com?subject=' + encodeURIComponent('Listing correction for ' + org.name) +
    '&body=' + encodeURIComponent([org.name, url, '', 'Suggested correction', '', 'Public source (if available)', ''].join('\r\n'));
  const located = Number.isFinite(org.lat) && Number.isFinite(org.lng) && Math.abs(org.lat) <= 90 && Math.abs(org.lng) <= 180;
  return `<!doctype html>
${marker}
<html lang="en"><head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${escape(title)}</title>
<meta name="description" content="${escape(description)}">
<link rel="canonical" href="${url}">
<meta property="og:type" content="website"><meta property="og:url" content="${url}">
<meta property="og:title" content="${escape(title)}"><meta property="og:description" content="${escape(description)}">
<meta name="twitter:card" content="summary">
<meta name="referrer" content="strict-origin"><link rel="stylesheet" href="/map/measurement.css">
<link rel="icon" href="/map/favicon.svg"><link rel="stylesheet" href="/map/styles.css">
<link rel="stylesheet" href="/map/brand-system.css"><link rel="stylesheet" href="/map/profile-pages.css?v=${profileStyleVersion}">
<script defer src="/map/app-shell.js"></script><script defer src="${measurementScript}"></script>
<script type="application/ld+json">${JSON.stringify(schema).replace(/</g, '\\u003c')}</script>
</head><body class="organisation-profile">
<a class="skip-link" href="#profile">Skip to organisation</a>
<main class="policy-page" id="profile" tabindex="-1">
<nav aria-label="Breadcrumb"><a href="/directory/">Organisation directory</a></nav>
<h1>${escape(org.name)}</h1>
<p>${escape(description)}</p>
<dl>${details}</dl>
${founded ? '<p>' + link(org.founding_year_source_url, founded + ' (source)', 'source_open') + '</p>' : ''}
${source ? '<p>Public source · ' + link(source, new URL(source).hostname, 'source_open') + '</p>' : '<p>Supporting source not yet recorded.</p>'}
<nav class="profile-actions" aria-label="Organisation links">
${website ? link(website, 'Visit organisation website', 'website_open') : ''}
${located ? link('/map/?organisation=' + org.id, 'Show on map', 'profile_to_map') : ''}
</nav>
${nearby.length ? `<section class="profile-nearby" aria-labelledby="nearby-title">
<h2 id="nearby-title">More organisations in ${escape(org.city)}</h2>
<ul>${nearby.map(other => '<li>' + link(pathFor(other), other.name) +
  (other.type ? '<span>' + escape(other.type) + '</span>' : '') + '</li>').join('')}</ul>
</section>` : ''}
</main>
<footer class="site-footer"><a href="/map/about.html">About the map</a><a href="/map/privacy.html">Privacy</a><a href="/map/cookies.html">Cookies</a><a href="${escape(correction)}">Suggest a correction</a></footer>
</body></html>\n`;
}

for (const org of rows) {
  if (!check) mkdirSync(folder + '/' + org.id, { recursive: true });
  update(folder + '/' + org.id + '/index.html', render(org));
}
// Remove only pages written by this generator after a public listing is withdrawn.
for (const entry of readdirSync(folder, {withFileTypes: true})) {
  if (!entry.isDirectory() || ids.has(entry.name)) continue;
  const dir = folder + '/' + entry.name;
  if (readdirSync(dir).join() !== 'index.html' || !readFileSync(dir + '/index.html','utf8').includes(marker)) continue;
  if (check) stale.push(dir + '/index.html');
  else {
    unlinkSync(dir + '/index.html');
    rmdirSync(dir);
  }
}
const profileIndex = 'window.MCHPublishedProfiles = new Set(' + JSON.stringify([...ids].sort(), null, 2) + ');\n';
update('map/published-profiles.js', profileIndex);
const profileIndexVersion = createHash('sha256').update(profileIndex).digest('hex').slice(0, 12);
const cards = rows.map(org => {
  const source = httpsUrl(org.sourceUrl);
  return `<article class="card"><h2>${link(pathFor(org), org.name)}</h2><p>${escape([org.type, org.city, org.country].filter(Boolean).join(' · '))}</p><p>${escape(org.description)}</p>${source ? '<p>' + link(source, 'Public source for ' + org.name) + '</p>' : ''}</article>`;
}).join('\n');
for (const file of ['directory/index.html', 'map/directory.html']) {
  const html = readFileSync(file, 'utf8');
  const region = /(<div id="results" class="results">)[\s\S]*?(<\/div>)/;
  if (!region.test(html)) throw new Error('Missing static directory in ' + file);
  update(file, html.replace(region, (_, start, end) => start + cards + end));
}
// GitHub Pages caches static assets. Update every entry point when the consent script changes.
for (const file of ['map/index.html', 'map/directory.html', 'directory/index.html', 'map/cookies.html']) {
  const page = readFileSync(file, 'utf8');
  update(file, page.replace(/src="\/map\/published-profiles\.js(?:\?v=[a-f0-9]+)?"/g,
    'src="/map/published-profiles.js?v=' + profileIndexVersion + '"').replace(/src="\/map\/measurement\.js(?:\?v=[a-f0-9]+)?"/g, 'src="' + measurementScript + '"'));
}
const mapPages = ['/map/', '/map/network.html', '/map/about.html', ...rows.map(pathFor)];
function sitemap(paths) {
  return '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    paths.map(path => '  <url><loc>' + site + path + '</loc></url>').join('\n') + '\n</urlset>\n';
}
update('map/sitemap.xml', sitemap(mapPages));
update('sitemap.xml', sitemap(['/', '/about/', '/directory/', '/brand-book/', '/design-system/', ...mapPages]));
if (stale.length) {
  console.error(`Profile release files are out of date (${stale.length}): ${stale.slice(0, 8).join(', ')}`);
  process.exitCode = 1;
} else console.log((check ? 'Verified ' : 'Built ') + rows.length + ' organisation pages.');
